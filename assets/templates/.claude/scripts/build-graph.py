#!/usr/bin/env python3
"""Project graph: every file in the project as a node, every relationship between files as an edge.

A map to navigate with instead of grepping and opening files. Built deterministically from the files
themselves - no model, no network, no server, standard library only.

Nodes  = project files (source, tests, specs, ADRs, docs, Database/ design files, agents, skills, config).
Edges  = imports (Python via ast, JS/TS relative imports), markdown links, explicit path mentions,
         REQ-ID coverage (tasks -> requirements, tests -> requirements), skill/agent invocations, plus a few
         structural ones (spec chain requirements -> prd, design -> requirements, tasks -> design; test -> the
         source file it is named after). Every edge is tagged EXTRACTED (written in the files) or INFERRED
         (derived from a naming/layout convention). A reference to a file that does not exist becomes a
         `missing` node: a broken link, reported.
Never read: .env*, keys, certificates, databases, lockfiles, binaries, and the graph's own outputs.

Outputs (docs/knowledge-graph/, generated, deterministic - never edit by hand):
  graph.json         nodes + edges + communities; what the queries below read
  GRAPH_REPORT.md   god nodes (most connected), communities, broken references, orphans - read this first
  graph.html         interactive 3D view

Usage:
  build-graph.py [build] [--title NAME]   (re)build all three outputs
  build-graph.py check                    exit 1 if the outputs are stale (files changed since the build)
  build-graph.py query TERM [TERM ...]    ranked files matching the terms, with their neighbours
  build-graph.py explain FILE             one file: what it is, what it points to, what points to it
  build-graph.py path A B                 shortest chain of relationships between two files
Exit codes: 0 answered, 3 ambiguous name (candidates listed), 4 no match / no graph yet.
"""
import argparse
import ast
import collections
import hashlib
import html
import json
import os
import re
import subprocess
import sys
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):
    _stream.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles default to cp1252

OUT_DIR = "docs/knowledge-graph"
OUTPUTS = ("graph.json", "GRAPH_REPORT.md", "graph.html")
TEMPLATE = Path(__file__).with_name("graph-view.html")
SCHEMA = 1
MAX_BYTES = 300_000
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", "env", "dist", "build", ".next", ".nuxt",
             "target", "coverage", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".idea", ".vscode", ".gradle"}
SKIP_NAMES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "Cargo.lock", "Gemfile.lock",
              "composer.lock", "go.sum", "uv.lock", "settings.local.json"}
SKIP_SUFFIXES = (".pem", ".key", ".p12", ".pfx", ".crt", ".cer", ".sqlite", ".sqlite3", ".db", ".min.js", ".map",
                 ".lock", ".tmpl")
CODE_EXT = {".py", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".go", ".java", ".kt", ".rb", ".rs", ".cs", ".php",
            ".swift", ".c", ".h", ".cpp", ".hpp", ".sql", ".sh", ".ps1", ".vue", ".svelte"}
DOC_EXT = {".md", ".mdx", ".rst", ".txt"}
CONFIG_EXT = {".json", ".yml", ".yaml", ".toml", ".ini", ".cfg", ".html", ".css", ".scss"}
JS_EXT = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte"]

HEADING = re.compile(r"^(#{1,3})\s+(.+?)\s*#*\s*$")
STATUS = re.compile(r"^\s*Status:\s*([^|\n]+)", re.I | re.M)
REQ_ID = re.compile(r"\bREQ-\d+\b")
REQ_DEF = re.compile(r"^\s*-?\s*\**(REQ-\d+)\**\s*:", re.M)
MD_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
TICK_PATH = re.compile(r"`([\w@.\-]+(?:/[\w@.\-]+)*\.(?:py|js|jsx|ts|tsx|mjs|md|json|yml|yaml|html|css|sql|sh|toml))`")
TICK_SKILL = re.compile(r"`/([a-z][\w-]+)`")
TICK_WORD = re.compile(r"`([a-z][a-z-]+)`")
JS_IMPORT = re.compile(r"""(?:\bfrom\s+|\brequire\s*\(\s*|\bimport\s*\(\s*|^\s*import\s+)['"]([^'"]+)['"]""", re.M)
SYMBOL = re.compile(r"^\s*(?:export\s+)?(?:default\s+)?(?:public\s+|private\s+|protected\s+|internal\s+|static\s+|abstract\s+|final\s+|async\s+"
                    r"|sealed\s+|partial\s+|readonly\s+|open\s+|data\s+|file\s+)*"
                    r"(?:class|interface|struct|enum|record|trait|fn|def|func|function|type)\s+(?:(?:class|struct)\s+)?([A-Za-z_]\w*)", re.M)
IDENT = re.compile(r"[A-Za-z_]\w*")
CAMEL_TESTS = re.compile(r"(tests?|spec|specs)$")
SQL_OBJECT = re.compile(r"create\s+(?:or\s+replace\s+)?(?:table|view|function|procedure|index|type)\s+(?:if\s+not\s+exists\s+)?([\w.\"]+)", re.I)
GENERATED_NOTE = "Generated by .claude/scripts/build-graph.py - never edit by hand."


# ---------------------------------------------------------------- discovery
def excluded(rel: str) -> bool:
    p = Path(rel)
    name = p.name
    if any(part in SKIP_DIRS for part in p.parts[:-1]):
        return True
    if name.startswith(".env") or name in SKIP_NAMES or name.lower().endswith(SKIP_SUFFIXES):
        return True
    if "id_rsa" in name or "id_ed25519" in name or "credentials" in name.lower() and p.suffix in {".json", ".yml", ".yaml"}:
        return True
    if rel.startswith(OUT_DIR + "/") and name in OUTPUTS:
        return True
    return p.suffix.lower() not in CODE_EXT | DOC_EXT | CONFIG_EXT


def list_files(root: Path) -> list[str]:
    names: list[str] = []
    try:
        r = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=root, capture_output=True, check=True)
        names = [n for n in r.stdout.decode("utf-8", "replace").split("\0") if n]
    except (OSError, subprocess.CalledProcessError):
        for dirpath, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            names += [Path(dirpath, f).relative_to(root).as_posix() for f in files]
    out = []
    for n in sorted(set(names)):
        f = root / n
        if not excluded(n) and f.is_file() and f.stat().st_size <= MAX_BYTES:
            out.append(n)
    return out


def read(root: Path, rel: str) -> str | None:
    data = (root / rel).read_bytes()
    if b"\0" in data:
        return None
    return data.decode("utf-8", errors="replace")


# ---------------------------------------------------------------- classification
def is_test(rel: str) -> bool:
    p = Path(rel)
    name = p.name.lower()
    return (any(part in {"test", "tests", "__tests__", "spec", "specs_e2e", "e2e"} for part in p.parts[:-1])
            or name.startswith("test_") or re.search(r"(_test|\.test|\.spec|_spec)\.\w+$", name) is not None)


def classify(rel: str) -> tuple[str, str]:
    """(kind, feature) from the path - the scaffold's layout fixes where things live."""
    p = Path(rel)
    parts = p.parts
    if parts[0] == "Database":
        return "database", ""
    if parts[:2] == ("docs", "specs") and len(parts) >= 3:
        if parts[2] == "_templates":
            return "template", ""
        if len(parts) >= 4:
            return "spec", parts[2]
        return "spec", ""
    if parts[:2] == ("docs", "adr"):
        return "adr", ""
    if parts[:2] == (".claude", "agents"):
        return "agent", ""
    if parts[:2] == (".claude", "skills"):
        return "skill", ""
    if parts[0] == ".claude":
        return "script" if p.suffix in CODE_EXT else "config", ""
    if is_test(rel):
        return "test", ""
    if p.suffix in CODE_EXT:
        return "source", ""
    if p.suffix in DOC_EXT:
        return "doc", ""
    return "config", ""


def community_of(rel: str, kind: str, feature: str) -> str:
    parts = Path(rel).parts
    if kind == "spec" and feature:
        return f"spec:{feature}"
    if len(parts) == 1:
        return "root"
    if parts[0] in {"src", "app", "lib", "packages", "apps", "docs", ".claude"} and len(parts) > 2:
        return "/".join(parts[:2])
    return parts[0]


# ---------------------------------------------------------------- per-file extraction
FRONTMATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)


def md_info(text: str) -> dict:
    title, headings = "", []
    fm = FRONTMATTER.match(text)
    meta = {}
    if fm:  # agents and skills: the frontmatter's name/description is the best summary there is
        meta = dict(re.findall(r"^(name|description):\s*(.+)$", fm.group(1), re.M))
        text = text[fm.end():]
    in_fence = False
    summary = ""
    for line in text.splitlines():
        if line.strip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = HEADING.match(line)
        if m:
            if not title and len(m.group(1)) == 1:
                title = m.group(2)
            elif len(m.group(1)) >= 2:
                headings.append(m.group(2))
            continue
        s = line.strip()
        if not summary and s and s[0] not in "|>-*<`" and not s.lower().startswith("status:"):
            summary = re.sub(r"\s+", " ", s)[:200]
    st = STATUS.search(text)
    if meta.get("description"):
        summary = re.sub(r"\s+", " ", meta["description"])[:200]
    title = title or meta.get("name", "")
    return {"title": title, "headings": headings[:40], "summary": summary, "status": st.group(1).strip() if st else ""}


def py_info(text: str) -> tuple[list[str], str, list[tuple[str, int, str]]]:
    """symbols, module docstring (first line), imports as (module, level, name-or-'')."""
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return [], "", []
    symbols = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]
    doc = (ast.get_docstring(tree) or "").strip().splitlines()
    imports = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            imports += [(a.name, 0, "") for a in n.names]
        elif isinstance(n, ast.ImportFrom):
            imports += [(n.module or "", n.level, a.name) for a in n.names]
    return symbols, (doc[0][:200] if doc else ""), imports


def generic_symbols(rel: str, text: str) -> list[str]:
    names = SYMBOL.findall(text)
    if rel.endswith(".sql"):
        names += SQL_OBJECT.findall(text)
    return list(dict.fromkeys(names))


# ---------------------------------------------------------------- build
class Graph:
    def __init__(self):
        self.nodes: dict[str, dict] = {}
        self.edges: dict[tuple, dict] = {}

    def edge(self, src: str, dst: str, label: str, confidence: str) -> None:
        if src == dst:
            return
        key = (src, dst, label)
        if key not in self.edges:
            self.edges[key] = {"source": src, "target": dst, "label": label, "confidence": confidence}
        elif confidence == "EXTRACTED":
            self.edges[key]["confidence"] = "EXTRACTED"


def resolve_py(files: set[str], rel: str, module: str, level: int, name: str) -> str | None:
    base = Path(rel).parent
    if level:
        for _ in range(level - 1):
            base = base.parent
        roots = [base]
    else:
        roots = [Path("."), Path("src"), Path("lib"), Path("app"), base]
    pieces = module.split(".") if module else []
    cands = []
    for r in roots:
        stem = r.joinpath(*pieces)
        if name and (level or pieces):
            cands += [stem / f"{name}.py", stem / name / "__init__.py"]   # `from pkg import mod`
        cands += [stem.with_suffix(".py"), stem / "__init__.py"]
    for c in cands:
        s = c.as_posix().lstrip("./") if c.as_posix().startswith("./") else c.as_posix()
        if s in files and s != rel:
            return s
    return None


def resolve_js(files: set[str], rel: str, spec: str) -> str | None:
    if not spec.startswith("."):
        return None
    base = (Path(rel).parent / spec)
    norm = os.path.normpath(base.as_posix()).replace("\\", "/")
    cands = [norm] + [norm + e for e in JS_EXT] + [f"{norm}/index{e}" for e in JS_EXT]
    for c in cands:
        if c in files:
            return c
    return None


def link_target(files: set[str], dirs: set[str], rel: str, raw: str) -> tuple[str | None, str | None]:
    """(existing file, or None) and (normalized missing path, or None) for a markdown link target."""
    target = raw.split("#")[0].split("?")[0]
    if not target or re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("//"):
        return None, None
    rooted = target.startswith("/")
    norm = os.path.normpath(target.lstrip("/") if rooted else (Path(rel).parent / target).as_posix()).replace("\\", "/")
    if norm.startswith(".."):
        return None, None
    if norm in files:
        return norm, None
    if norm in dirs or "<" in norm or ">" in norm or "{" in norm or "*" in norm:
        return None, None
    if Path(norm).suffix.lower() in CODE_EXT | DOC_EXT | CONFIG_EXT:
        return None, norm
    return None, None


def build(root: Path) -> dict:
    files = list_files(root)
    fileset = set(files)
    dirs = {d.as_posix() for f in files for d in Path(f).parents if d.as_posix() != "."}
    g = Graph()
    texts: dict[str, str] = {}
    for rel in files:
        text = read(root, rel)
        if text is None:
            continue
        texts[rel] = text
        kind, feature = classify(rel)
        p = Path(rel)
        node = {"id": rel, "label": p.name if (p.name not in {"SKILL.md", "README.md", "STATUS.md"} or not p.parent.name) else f"{p.parent.name}/{p.name}",
                "type": kind, "feature": feature, "community": community_of(rel, kind, feature),
                "lines": text.count("\n") + 1, "hash": hashlib.sha1(text.encode("utf-8")).hexdigest()[:10],
                "title": "", "status": "", "summary": "", "headings": [], "symbols": [], "req_ids": []}
        if p.suffix.lower() in DOC_EXT:
            node.update(md_info(text))
        elif p.suffix == ".py":
            node["symbols"], node["summary"], _ = py_info(text)
        elif p.suffix.lower() in CODE_EXT:
            node["symbols"] = generic_symbols(rel, text)
        node["req_ids"] = sorted(set(REQ_ID.findall(text)))
        node["symbols"] = node["symbols"][:30]
        obs = [x for x in (node["title"], node["status"] and f"Status: {node['status']}", node["summary"],
                           node["symbols"] and "Defines: " + ", ".join(node["symbols"][:12]),
                           node["headings"] and "Sections: " + ", ".join(node["headings"][:10]),
                           node["req_ids"] and "REQ-IDs: " + ", ".join(node["req_ids"][:10])) if x]
        node["observations"] = obs
        g.nodes[rel] = node

    # ---- imports
    for rel, text in texts.items():
        suffix = Path(rel).suffix.lower()
        if suffix == ".py":
            for module, level, name in py_info(text)[2]:
                tgt = resolve_py(fileset, rel, module, level, name)
                if tgt:
                    g.edge(rel, tgt, "imports", "EXTRACTED")
        elif suffix in set(JS_EXT):
            for spec in JS_IMPORT.findall(text):
                tgt = resolve_js(fileset, rel, spec)
                if tgt:
                    g.edge(rel, tgt, "imports", "EXTRACTED")

    # ---- links, path mentions, skill/agent invocations (docs, skills, agents, config text)
    by_base = collections.defaultdict(list)
    for f in texts:
        by_base[Path(f).name].append(f)
    agents = {Path(f).stem for f in texts if f.startswith(".claude/agents/")}
    skills = {Path(f).parent.name for f in texts if f.startswith(".claude/skills/") and f.endswith("SKILL.md")}
    for rel, text in texts.items():
        if Path(rel).suffix.lower() not in DOC_EXT:
            continue
        for raw in MD_LINK.findall(text):
            found, missing = link_target(fileset, dirs, rel, raw)
            if found:
                g.edge(rel, found, "links_to", "EXTRACTED")
            elif missing:
                g.nodes.setdefault(missing, {"id": missing, "label": Path(missing).name, "type": "missing", "feature": "",
                                             "community": "missing", "observations": ["Referenced but not found in the project"],
                                             "summary": "", "symbols": [], "headings": [], "req_ids": [], "title": "", "status": ""})
                g.edge(rel, missing, "links_to", "EXTRACTED")
        for path in TICK_PATH.findall(text):
            for cand in (path, os.path.normpath((Path(rel).parent / path).as_posix()).replace("\\", "/")):
                if cand in fileset:
                    g.edge(rel, cand, "mentions", "EXTRACTED")
                    break
            else:
                if "/" not in path and len(by_base.get(path, [])) == 1:
                    g.edge(rel, by_base[path][0], "mentions", "INFERRED")
        if rel.startswith((".claude/skills/", ".claude/agents/", "docs/", "CLAUDE.md", "AGENTS.md", "README.md", "SKILL.md")):
            for name in TICK_SKILL.findall(text):
                if name in skills:
                    g.edge(rel, f".claude/skills/{name}/SKILL.md", "invokes", "EXTRACTED")
            if rel.startswith((".claude/", "CLAUDE.md", "AGENTS.md")):
                for name in TICK_WORD.findall(text):
                    if name in agents and f".claude/agents/{name}.md" != rel:
                        g.edge(rel, f".claude/agents/{name}.md", "delegates_to", "INFERRED")

    # ---- REQ-ID coverage
    defined = collections.defaultdict(set)
    for rel, text in texts.items():
        if Path(rel).name == "requirements.md" and rel.startswith("docs/specs/"):
            for r in REQ_DEF.findall(text):
                defined[r].add(rel)
    for rel, text in texts.items():
        kind, feature = g.nodes[rel]["type"], g.nodes[rel]["feature"]
        if kind in {"template", "adr"} and not feature:
            continue
        ids = set(REQ_ID.findall(text))
        if not ids or Path(rel).name == "requirements.md":
            continue
        label = "covers" if Path(rel).name == "tasks.md" else ("verifies" if kind == "test" else "references_req")
        for r in ids:
            owners = defined.get(r, set())
            if kind == "spec" and feature:
                owners = {o for o in owners if o.startswith(f"docs/specs/{feature}/")}
            if len(owners) == 1:
                g.edge(rel, next(iter(owners)), label, "EXTRACTED")

    # ---- structural, INFERRED
    for rel, node in g.nodes.items():
        if node["type"] == "spec" and node["feature"]:
            d = f"docs/specs/{node['feature']}"
            chain = {"requirements.md": "prd.md", "design.md": "requirements.md", "tasks.md": "design.md",
                     "overview.html": "design.md", "findings-ledger.md": "tasks.md", "security-report.md": "design.md"}
            parent = chain.get(Path(rel).name)
            if parent and f"{d}/{parent}" in g.nodes:
                g.edge(rel, f"{d}/{parent}", "derives_from", "INFERRED")
    sources = collections.defaultdict(list)
    for rel, node in g.nodes.items():
        if node["type"] == "source":
            sources[Path(rel).stem.lower().replace("-", "_")].append(rel)
    for rel, node in g.nodes.items():
        if node["type"] == "test":
            stem = re.sub(r"(^test_|_test$|\.test$|\.spec$|_spec$)", "", Path(rel).stem.lower().replace("-", "_"))
            stem = re.sub(r"\.(test|spec)$", "", stem)
            if stem not in sources:
                stem = CAMEL_TESTS.sub("", stem)
            if len(sources.get(stem, [])) == 1:
                g.edge(rel, sources[stem][0], "tests", "INFERRED")

    # ---- code that names a type declared in exactly one other file (C#, Java, Go, ... have no import graph)
    declared = collections.defaultdict(set)
    for rel, node in g.nodes.items():
        if Path(rel).suffix.lower() in CODE_EXT and Path(rel).suffix != ".py":
            for sym in node["symbols"]:
                if len(sym) >= 4:
                    declared[sym].add(rel)
    unique = {sym: next(iter(f)) for sym, f in declared.items() if len(f) == 1}
    for rel, text in texts.items():
        if Path(rel).suffix.lower() in CODE_EXT and Path(rel).suffix != ".py":
            for ident in set(IDENT.findall(text)) & unique.keys():
                if unique[ident] != rel:
                    g.edge(rel, unique[ident], "uses", "INFERRED")

    # ---- documents that name a database object (pk_player, accounts.player) by its file stem
    objects = {}
    for rel, node in g.nodes.items():
        parts = Path(rel).parts
        if node["type"] == "database" and len(parts) >= 3 and Path(rel).suffix.lower() in DOC_EXT:
            name = Path(rel).stem
            if len(name) >= 5 and name.lower() != "readme":
                objects.setdefault(name, []).append(rel)
    if objects:
        pattern = re.compile(r"(?<![\w.])(" + "|".join(re.escape(n) for n in sorted(objects, key=len, reverse=True)) + r")(?![\w])")
        for rel, text in texts.items():
            if Path(rel).suffix.lower() not in DOC_EXT:
                continue
            for name in set(pattern.findall(text)):
                if len(objects[name]) == 1 and objects[name][0] != rel:
                    g.edge(rel, objects[name][0], "mentions", "EXTRACTED")

    # ---- last resort: a file nothing else relates to belongs to its folder's README/index
    linked = {e["source"] for e in g.edges.values()} | {e["target"] for e in g.edges.values()}
    for rel in sorted(g.nodes):
        if rel in linked or g.nodes[rel]["type"] == "missing":
            continue
        for parent in Path(rel).parents:
            hit = next((c for c in (f"{parent.as_posix()}/README.md", f"{parent.as_posix()}/index.md") if c in g.nodes and c != rel), None)
            if hit:
                g.edge(rel, hit, "part_of", "INFERRED")
                break

    edges = sorted(g.edges.values(), key=lambda e: (e["source"], e["target"], e["label"]))
    nodes = [g.nodes[k] for k in sorted(g.nodes)]
    return {"schema_version": SCHEMA, "generated_by": GENERATED_NOTE, "nodes": nodes, "links": edges}


# ---------------------------------------------------------------- analysis and rendering
def degrees(graph: dict) -> dict:
    d = collections.Counter()
    for e in graph["links"]:
        d[e["source"]] += 1
        d[e["target"]] += 1
    return d


def report(graph: dict) -> str:
    nodes, links = graph["nodes"], graph["links"]
    deg = degrees(graph)
    by_kind = collections.Counter(n["type"] for n in nodes)
    inferred = sum(1 for e in links if e["confidence"] == "INFERRED")
    out = ["# Project graph report (generated)", "",
           f"> {GENERATED_NOTE} Read this first, then query the graph instead of grepping: "
           "`build-graph.py query <terms>` / `explain <file>` / `path <a> <b>`.", "",
           f"{len(nodes)} files, {len(links)} relationships ({len(links) - inferred} extracted, {inferred} inferred)", "",
           "## Files by kind", "", "| Kind | Files |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sorted(by_kind.items())]
    out += ["", "## God nodes (most connected - what much of the project flows through)", "",
            "| File | Kind | Connections |", "|---|---|---|"]
    out += [f"| `{n['id']}` | {n['type']} | {deg[n['id']]} |"
            for n in sorted(nodes, key=lambda n: (-deg[n["id"]], n["id"]))[:12] if deg[n["id"]]]
    comms = collections.defaultdict(list)
    for n in nodes:
        comms[n["community"]].append(n)
    out += ["", "## Communities (a feature's specs, or a directory)", "", "| Community | Files | Most connected |", "|---|---|---|"]
    for c in sorted(comms):
        top = max(comms[c], key=lambda n: (deg[n["id"]], n["id"]))
        out.append(f"| {c} | {len(comms[c])} | `{top['id']}` |")
    missing = [n for n in nodes if n["type"] == "missing"]
    out += ["", "## Broken references (linked but not in the project)", ""]
    if missing:
        for n in missing:
            refs = sorted(e["source"] for e in links if e["target"] == n["id"])
            out.append(f"- `{n['id']}` <- {', '.join(f'`{r}`' for r in refs[:5])}")
    else:
        out.append("None.")
    orphans = [n["id"] for n in nodes if not deg[n["id"]] and n["type"] not in {"missing", "config"} and n["community"] != "root"]
    out += ["", "## Orphans (no relationship to any other file)", ""]
    out += [f"- `{o}`" for o in orphans[:30]] + ([f"- ... and {len(orphans) - 30} more"] if len(orphans) > 30 else []) if orphans else ["None."]
    return "\n".join(out) + "\n"


def render_html(graph: dict, title: str) -> str:
    if not TEMPLATE.is_file():
        sys.exit(f"{TEMPLATE} not found - it ships next to this script; re-run the scaffold to restore it")
    view = {"nodes": [{k: n[k] for k in ("id", "label", "type", "observations")} for n in graph["nodes"]],
            "links": [{"source": e["source"], "target": e["target"], "label": e["label"]} for e in graph["links"]]}
    # "</" is escaped so a file's text can never close the JSON <script> block ("<\/" is still valid JSON).
    data = json.dumps(view, ensure_ascii=False).replace("</", "<\\/")
    return TEMPLATE.read_text(encoding="utf-8").replace("__TITLE__", html.escape(title)).replace("__DATA__", data)


def outputs_for(root: Path, title: str) -> dict[str, str]:
    graph = build(root)
    return {"graph.json": json.dumps(graph, ensure_ascii=False, indent=1) + "\n",
            "GRAPH_REPORT.md": report(graph), "graph.html": render_html(graph, title)}


# ---------------------------------------------------------------- queries
def load(root: Path) -> dict | None:
    p = root / OUT_DIR / "graph.json"
    if not p.is_file():
        print("No graph yet - run: build-graph.py")
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def neighbours(graph: dict, nid: str):
    out = [(e["label"], e["target"], e["confidence"], ">") for e in graph["links"] if e["source"] == nid]
    inc = [(e["label"], e["source"], e["confidence"], "<") for e in graph["links"] if e["target"] == nid]
    return out, inc


def score(n: dict, terms: list[str]) -> tuple[int, list[str]]:
    s, why = 0, []
    for t in terms:
        for label, hay, w in (("path", n["id"], 3), ("name", n["label"], 4), ("title", n.get("title", ""), 4),
                              ("symbol", " ".join(n.get("symbols", [])), 3), ("req", " ".join(n.get("req_ids", [])), 3),
                              ("summary", n.get("summary", ""), 1)):
            if t in hay.lower():
                s += w
                why.append(label)
        for h in n.get("headings", []):
            if t in h.lower():
                s += 2
                why.append(f"section: {h}")
    return s, why


def cmd_query(root: Path, terms: list[str]) -> int:
    graph = load(root)
    if graph is None:
        return 4
    terms = [t.lower() for t in terms]
    hits = sorted(((s, n, w) for n in graph["nodes"] for s, w in [score(n, terms)] if s),
                  key=lambda h: (-h[0], h[1]["id"]))[:12]
    if not hits:
        print("No match. If the file is new, rebuild (build-graph.py); otherwise fall back to grep.")
        return 4
    for s, n, why in hits:
        print(f"{n['id']}  [{n['type']}{', ' + n['status'] if n.get('status') else ''}]  match: {', '.join(dict.fromkeys(why))}")
        if n.get("summary") or n.get("title"):
            print(f"    {n.get('title') or ''} {('- ' + n['summary']) if n.get('summary') else ''}".rstrip())
        out, inc = neighbours(graph, n["id"])
        rel = [f"{lab}> {o}" for lab, o, c, _ in out[:4]] + [f"<{lab} {o}" for lab, o, c, _ in inc[:3]]
        if rel:
            print("    " + "; ".join(rel))
    return 0


def resolve_name(graph: dict, name: str) -> tuple[dict | None, list[str]]:
    ids = [n["id"] for n in graph["nodes"]]
    name = name.replace("\\", "/").lstrip("./")
    if name in ids:
        return next(n for n in graph["nodes"] if n["id"] == name), []
    cands = [i for i in ids if i.endswith("/" + name) or Path(i).name == name] or [i for i in ids if name.lower() in i.lower()]
    if len(cands) == 1:
        return next(n for n in graph["nodes"] if n["id"] == cands[0]), []
    return None, cands


def cmd_explain(root: Path, name: str) -> int:
    graph = load(root)
    if graph is None:
        return 4
    node, cands = resolve_name(graph, name)
    if node is None:
        print(("Ambiguous - candidates:\n  " + "\n  ".join(cands[:15])) if cands else f"No file matches {name!r}.")
        return 3 if cands else 4
    print(f"{node['id']}  [{node['type']}] community: {node['community']}  {node.get('lines', '')} lines")
    for o in node["observations"]:
        print(f"  {o}")
    out, inc = neighbours(graph, node["id"])
    print("Points to:" if out else "Points to: nothing")
    for lab, o, conf, _ in out:
        print(f"  {lab} -> {o}  ({conf.lower()})")
    print("Pointed to by:" if inc else "Pointed to by: nothing")
    for lab, o, conf, _ in inc:
        print(f"  {o} -{lab}-> (this file)  ({conf.lower()})")
    return 0


def cmd_path(root: Path, a: str, b: str) -> int:
    graph = load(root)
    if graph is None:
        return 4
    na, ca = resolve_name(graph, a)
    nb, cb = resolve_name(graph, b)
    for n, c, name in ((na, ca, a), (nb, cb, b)):
        if n is None:
            print(("Ambiguous %r - candidates:\n  " % name + "\n  ".join(c[:15])) if c else f"No file matches {name!r}.")
            return 3 if c else 4
    adj = collections.defaultdict(list)
    for e in graph["links"]:
        adj[e["source"]].append((e["target"], f"-{e['label']}->"))
        adj[e["target"]].append((e["source"], f"<-{e['label']}-"))
    prev, queue = {na["id"]: None}, collections.deque([na["id"]])
    while queue:
        cur = queue.popleft()
        if cur == nb["id"]:
            break
        for nxt, lab in sorted(adj[cur]):
            if nxt not in prev:
                prev[nxt] = (cur, lab)
                queue.append(nxt)
    if nb["id"] not in prev:
        print(f"No relationship chain between {na['id']} and {nb['id']}.")
        return 4
    chain, cur = [], nb["id"]
    while prev[cur]:
        p, lab = prev[cur]
        chain.append(f"{p} {lab} {cur}")
        cur = p
    print("\n".join(reversed(chain)))
    return 0


# ---------------------------------------------------------------- main
def main() -> None:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", default=".")
    common.add_argument("--title", default=None, help="shown in the 3D view's top bar (default: the folder name)")
    known, rest = common.parse_known_args()
    if not rest or rest[0] not in {"build", "check", "query", "explain", "path", "-h", "--help"}:
        rest = ["build"] + rest
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], epilog="Global options (before or after the command): --root DIR, --title NAME")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    sub.add_parser("check")
    sub.add_parser("query").add_argument("terms", nargs="+")
    sub.add_parser("explain").add_argument("file")
    pp = sub.add_parser("path")
    pp.add_argument("a")
    pp.add_argument("b")
    args = ap.parse_args(rest)
    root = Path(known.root).resolve()
    title = known.title or root.name

    if args.cmd == "query":
        sys.exit(cmd_query(root, args.terms))
    if args.cmd == "explain":
        sys.exit(cmd_explain(root, args.file))
    if args.cmd == "path":
        sys.exit(cmd_path(root, args.a, args.b))

    out = outputs_for(root, title)
    out_dir = root / OUT_DIR
    if args.cmd == "check":
        # graph.html embeds the --title, so it is derived from graph.json and not compared here.
        stale = [n for n in OUTPUTS if n != "graph.html"
                 and (not (out_dir / n).is_file() or (out_dir / n).read_text(encoding="utf-8") != out[n])]
        print(f"STALE graph ({', '.join(stale)}) - run: build-graph.py" if stale else "PASS graph is current")
        sys.exit(1 if stale else 0)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in out.items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    g = json.loads(out["graph.json"])
    broken = sum(1 for n in g["nodes"] if n["type"] == "missing")
    print(f"Wrote {OUT_DIR}/{{graph.json,GRAPH_REPORT.md,graph.html}} ({len(g['nodes'])} files, {len(g['links'])} relationships"
          + (f", {broken} broken reference(s)" if broken else "") + ")")


if __name__ == "__main__":
    main()
